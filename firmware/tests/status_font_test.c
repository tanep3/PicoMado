#include "status_font.h"
#include <assert.h>
#include <stdbool.h>
#include <stdio.h>
#include <string.h>
int main(void){
    static const uint8_t legacy[][5]={
    {0x7e,0x11,0x11,0x11,0x7e}, // A
    {0x7f,0x49,0x49,0x49,0x36}, // B
    {0x3e,0x41,0x41,0x41,0x22}, // C
    {0x7f,0x41,0x41,0x22,0x1c}, // D
    {0x7f,0x49,0x49,0x49,0x41}, // E
    {0x7f,0x09,0x09,0x09,0x01}, // F
    {0x3e,0x41,0x49,0x49,0x7a}, // G
    {0x7f,0x08,0x08,0x08,0x7f}, // H
    {0x41,0x41,0x7f,0x41,0x41}, // I
    {0x20,0x40,0x41,0x3f,0x01}, // J
    {0x7f,0x08,0x14,0x22,0x41}, // K
    {0x7f,0x40,0x40,0x40,0x40}, // L
    {0x7f,0x02,0x0c,0x02,0x7f}, // M
    {0x7f,0x04,0x08,0x10,0x7f}, // N
    {0x3e,0x41,0x41,0x41,0x3e}, // O
    {0x7f,0x09,0x09,0x09,0x06}, // P
    {0x3e,0x41,0x51,0x21,0x5e}, // Q
    {0x7f,0x09,0x19,0x29,0x46}, // R
    {0x46,0x49,0x49,0x49,0x31}, // S
    {0x01,0x01,0x7f,0x01,0x01}, // T
    {0x3f,0x40,0x40,0x40,0x3f}, // U
    {0x1f,0x20,0x40,0x20,0x1f}, // V
    {0x7f,0x20,0x18,0x20,0x7f}, // W
    {0x63,0x14,0x08,0x14,0x63}, // X
    {0x03,0x04,0x78,0x04,0x03}, // Y
    {0x61,0x51,0x49,0x45,0x43}, // Z
    };
    for(unsigned c=0;c<256;c++){
        const uint8_t *g=pm_status_glyph((unsigned char)c);
        bool supported=(c>='A'&&c<='Z')||(c>='0'&&c<='9');
        assert((g!=NULL)==supported);
        if(g){unsigned ink=0;for(unsigned col=0;col<5;col++){assert(!(g[col]&0x80));ink|=g[col];}assert(ink);}
        if(c>='A'&&c<='Z')assert(!memcmp(g,legacy[c-'A'],5));
    }
    for(char a='0';a<='9';a++)for(char b=a+1;b<='9';b++)
        assert(memcmp(pm_status_glyph(a),pm_status_glyph(b),5));
    const char *two[]={".###.","#...#","....#","...#.","..#..",".#...","#####"};
    for(unsigned y=0;y<7;y++)for(unsigned x=0;x<5;x++)
        assert(!!(pm_status_glyph('2')[x]&(1u<<y))==(two[y][x]=='#'));
    puts("PASS local font: legacy A-Z unchanged, distinct digits0-9, digit2 rows, all256 byte bounds");
    return 0;
}
