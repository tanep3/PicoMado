#!/usr/bin/env python3
"""Fixed two-line local switch label; same installed font as status_bitmaps.h."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import hashlib
font_file=Path('/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc')
image=Image.new('1',(128,56),0)
draw=ImageDraw.Draw(image)
for text,size,top,height in [('Pico窓',22,0,26),('切り替え中',24,28,28)]:
    font=ImageFont.truetype(str(font_file),size)
    box=draw.textbbox((0,0),text,font=font)
    draw.text(((128-(box[2]-box[0]))//2-box[0],top+(height-(box[3]-box[1]))//2-box[1]),text,font=font,fill=1)
packed=[]
for y in range(56):
    for x in range(0,128,8):packed.append(sum(bool(image.getpixel((x+b,y)))<<(7-b) for b in range(8)))
out=['#pragma once','#include <stdbool.h>','#include <stdint.h>',
     '// Pico窓 / 切り替え中. Generated by tools/make_switch_bitmap.py.',
     '// NotoSansCJK-Regular.ttc SHA256 '+hashlib.sha256(font_file.read_bytes()).hexdigest(),
     '#define PM_SWITCH_BITMAP_W 128u','#define PM_SWITCH_BITMAP_H 56u',
     'static const uint8_t pm_switch_bitmap[896] = {']
for at in range(0,len(packed),16):out.append('    '+','.join('0x%02x'%v for v in packed[at:at+16])+',')
out+=['};','static inline bool pm_switch_bitmap_ink(unsigned x,unsigned y,unsigned width,unsigned height){',
      '    if(width<PM_SWITCH_BITMAP_W || height<PM_SWITCH_BITMAP_H)return false;',
      '    unsigned left=(width-PM_SWITCH_BITMAP_W)/2,top=(height-PM_SWITCH_BITMAP_H)/2;',
      '    if(x<left || y<top || x-left>=PM_SWITCH_BITMAP_W || y-top>=PM_SWITCH_BITMAP_H)return false;',
      '    unsigned bit=(y-top)*PM_SWITCH_BITMAP_W+x-left;',
      '    return (pm_switch_bitmap[bit/8] & (0x80u>>(bit&7)))!=0;','}']
Path(__file__).resolve().parents[1].joinpath('src/switch_bitmap.h').write_text('\n'.join(out)+'\n')
